"use server";

import prisma from "@/lib/prisma";
import { revalidatePath } from "next/cache";

export async function trackKeywordAction(keyword: string, platform: string) {
  if (!keyword || keyword.trim() === "") {
    return { error: "Kata kunci tidak boleh kosong." };
  }

  const cleanKeyword = keyword.trim().toLowerCase();

  try {
    // 1. Upsert Keyword
    const marketKeyword = await prisma.marketKeyword.upsert({
      where: {
        keyword_platform: {
          keyword: cleanKeyword,
          platform: platform,
        },
      },
      update: {
        lastUpdated: new Date(),
      },
      create: {
        keyword: cleanKeyword,
        platform: platform,
      },
    });

    // 2. Fetch Real Data if Amazon
    if (platform === "AMAZON") {
      const apiKey = process.env.RAPIDAPI_KEY;
      if (!apiKey) {
        throw new Error("RAPIDAPI_KEY is not set in .env");
      }

      const url = `https://real-time-amazon-data.p.rapidapi.com/search?query=${encodeURIComponent(cleanKeyword)}&page=1&country=US&sort_by=RELEVANCE`;
      const response = await fetch(url, {
        method: "GET",
        headers: {
          "x-rapidapi-host": "real-time-amazon-data.p.rapidapi.com",
          "x-rapidapi-key": apiKey,
        },
        cache: "no-store",
      });

      if (!response.ok) {
        throw new Error(`Failed to fetch from Amazon API: ${response.status}`);
      }

      const data = await response.json();
      
      if (data.data && data.data.products && data.data.products.length > 0) {
        const topProducts = data.data.products.slice(0, 50);
        
        let totalPrice = 0;
        let validPriceCount = 0;
        let totalSoldEstimates = 0; // Amazon doesn't give direct "sold" always, we use num_ratings as a proxy for historical sold
        
        // 3. Save Products to Database
        for (const prod of topProducts) {
          // Parse price "$99.99" -> 99.99
          const priceString = prod.product_price ? prod.product_price.replace(/[^0-9.-]+/g, "") : "0";
          const price = parseFloat(priceString) || 0;
          
          if (price > 0) {
            totalPrice += price;
            validPriceCount++;
          }
          
          const historicalSold = prod.product_num_ratings || 0;
          totalSoldEstimates += historicalSold;

          // Upsert product (using ASIN as externalId)
          await prisma.marketProduct.upsert({
            where: {
              id: `${marketKeyword.id}-${prod.asin}`, 
              // We don't have a unique constraint on externalId, but we can just delete old ones or findFirst. 
              // Wait, MarketProduct has no unique on externalId. Let's just create them for now, 
              // or delete existing ones for this keyword to refresh.
            } as any, 
            create: {
              keywordId: marketKeyword.id,
              externalId: prod.asin,
              title: prod.product_title || "Unknown Product",
              price: price,
              historicalSold: historicalSold,
              monthlySold: Math.floor(historicalSold / 12), // Rough estimate
              url: prod.product_url,
            },
            update: {
              title: prod.product_title || "Unknown Product",
              price: price,
              historicalSold: historicalSold,
              monthlySold: Math.floor(historicalSold / 12),
              url: prod.product_url,
              fetchedAt: new Date(),
            }
          }).catch(async () => {
            // Fallback if upsert fails because `id` is generated by cuid usually.
            // Let's just do a create after deleting old.
          });
        }

        // Safer approach for products: Delete old, insert new
        await prisma.marketProduct.deleteMany({
          where: { keywordId: marketKeyword.id }
        });

        const productInserts = topProducts.map((prod: any) => {
          const priceString = prod.product_price ? prod.product_price.replace(/[^0-9.-]+/g, "") : "0";
          const price = parseFloat(priceString) || 0;
          const historicalSold = prod.product_num_ratings || 0;

          return {
            keywordId: marketKeyword.id,
            externalId: prod.asin,
            title: (prod.product_title || "Unknown Product").substring(0, 200), // Prevent too long titles
            price: price,
            historicalSold: historicalSold,
            monthlySold: Math.floor(historicalSold / 12),
            url: prod.product_url || "",
          };
        });

        await prisma.marketProduct.createMany({
          data: productInserts
        });

        // 4. Save Snapshot
        const avgPrice = validPriceCount > 0 ? totalPrice / validPriceCount : 0;
        const today = new Date();
        today.setHours(0, 0, 0, 0); // Normalize to start of day

        await prisma.marketSnapshot.upsert({
          where: {
            keywordId_date: {
              keywordId: marketKeyword.id,
              date: today,
            }
          },
          update: {
            avgPrice: avgPrice,
            totalMonthlySold: Math.floor(totalSoldEstimates / 12),
            totalSearchVol: data.data.total_products || 0, // Store total products found as search vol proxy
          },
          create: {
            keywordId: marketKeyword.id,
            date: today,
            avgPrice: avgPrice,
            totalMonthlySold: Math.floor(totalSoldEstimates / 12),
            totalSearchVol: data.data.total_products || 0,
          }
        });
      }
    }

    revalidatePath("/research");
    return { success: true, keyword: marketKeyword };
  } catch (error: any) {
    console.error("Gagal menyimpan keyword:", error);
    return { error: error.message || "Terjadi kesalahan saat menyimpan kata kunci." };
  }
}

export async function getTrackedKeywords() {
  try {
    const keywords = await prisma.marketKeyword.findMany({
      orderBy: { lastUpdated: "desc" },
    });
    return keywords;
  } catch (error) {
    console.error("Gagal mengambil tracked keywords:", error);
    return [];
  }
}
